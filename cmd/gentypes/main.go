package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"strings"

	"github.com/alexcaulfield/setlistify/pkg/apitypes"
	"github.com/alexcaulfield/setlistify/pkg/setlistfm"
	spotifyclient "github.com/zmb3/spotify/v2"
)

type generator struct {
	types      map[reflect.Type]string
	order      []reflect.Type
	customName map[reflect.Type]string
}

func newGenerator() *generator {
	return &generator{
		types:      make(map[reflect.Type]string),
		customName: make(map[reflect.Type]string),
	}
}

func (g *generator) registerNamed(t reflect.Type, name string) {
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	g.customName[t] = name
	g.register(t)
}

func (g *generator) register(t reflect.Type) {
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}

	if _, exists := g.types[t]; exists {
		return
	}

	// We only name and declare struct types
	if t.Kind() != reflect.Struct {
		return
	}

	name := g.customName[t]
	if name == "" {
		name = t.Name()
	}
	if name == "" {
		return
	}

	g.types[t] = name
	g.order = append(g.order, t)

	// Recursively register referenced struct types
	for i := 0; i < t.NumField(); i++ {
		field := t.Field(i)
		if !field.IsExported() {
			continue
		}
		ft := field.Type
		for ft.Kind() == reflect.Pointer || ft.Kind() == reflect.Slice || ft.Kind() == reflect.Array {
			ft = ft.Elem()
		}
		if ft.Kind() == reflect.Map {
			kt := ft.Key()
			vt := ft.Elem()
			for kt.Kind() == reflect.Pointer || kt.Kind() == reflect.Slice {
				kt = kt.Elem()
			}
			for vt.Kind() == reflect.Pointer || vt.Kind() == reflect.Slice {
				vt = vt.Elem()
			}
			if kt.Kind() == reflect.Struct {
				g.register(kt)
			}
			if vt.Kind() == reflect.Struct {
				g.register(vt)
			}
			continue
		}
		if ft.Kind() == reflect.Struct {
			g.register(ft)
		}
	}
}

func (g *generator) typeToTS(t reflect.Type) string {
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}

	switch t.Kind() {
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number"
	case reflect.String:
		return "string"
	case reflect.Slice, reflect.Array:
		elem := g.typeToTS(t.Elem())
		if strings.Contains(elem, " ") || strings.Contains(elem, "|") {
			return fmt.Sprintf("(%s)[]", elem)
		}
		return fmt.Sprintf("%s[]", elem)
	case reflect.Map:
		key := g.typeToTS(t.Key())
		val := g.typeToTS(t.Elem())
		return fmt.Sprintf("Record<%s, %s>", key, val)
	case reflect.Interface:
		return "unknown"
	case reflect.Struct:
		if name, ok := g.types[t]; ok {
			return name
		}
		if t.PkgPath() == "time" && t.Name() == "Time" {
			return "string"
		}
		return "Record<string, unknown>"
	default:
		return "unknown"
	}
}

func (g *generator) generate() ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by cmd/gentypes. DO NOT EDIT.\n\n")

	for _, t := range g.order {
		name := g.types[t]
		buf.WriteString(fmt.Sprintf("export interface %s {\n", name))

		var fields []reflect.StructField
		collectFields(t, &fields)

		for _, f := range fields {
			jsonTag := f.Tag.Get("json")
			if jsonTag == "-" {
				continue
			}

			tagParts := strings.Split(jsonTag, ",")
			fieldName := tagParts[0]
			if fieldName == "" {
				fieldName = f.Name
			}

			isOptional := false
			for _, opt := range tagParts[1:] {
				if opt == "omitempty" {
					isOptional = true
					break
				}
			}
			if f.Type.Kind() == reflect.Pointer {
				isOptional = true
			}

			tsType := g.typeToTS(f.Type)
			optChar := ""
			if isOptional {
				optChar = "?"
			}

			buf.WriteString(fmt.Sprintf("  %s%s: %s;\n", fieldName, optChar, tsType))
		}

		buf.WriteString("}\n\n")
	}

	return buf.Bytes(), nil
}

func collectFields(t reflect.Type, acc *[]reflect.StructField) {
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		if !f.IsExported() {
			continue
		}
		if f.Anonymous {
			ft := f.Type
			for ft.Kind() == reflect.Pointer {
				ft = ft.Elem()
			}
			if ft.Kind() == reflect.Struct {
				collectFields(ft, acc)
				continue
			}
		}
		*acc = append(*acc, f)
	}
}

func main() {
	g := newGenerator()

	// Register Spotify types with clean exported names
	g.registerNamed(reflect.TypeOf(spotifyclient.Followers{}), "SpotifyFollowers")
	g.registerNamed(reflect.TypeOf(spotifyclient.Image{}), "SpotifyImage")
	g.registerNamed(reflect.TypeOf(spotifyclient.SimpleArtist{}), "SpotifySimpleArtist")
	g.registerNamed(reflect.TypeOf(spotifyclient.FullArtist{}), "SpotifyFullArtist")
	g.registerNamed(reflect.TypeOf(spotifyclient.User{}), "SpotifyUser")
	g.registerNamed(reflect.TypeOf(spotifyclient.PrivateUser{}), "SpotifyPrivateUser")

	// Register Setlist.fm types
	g.registerNamed(reflect.TypeOf(setlistfm.Coords{}), "SetlistCoords")
	g.registerNamed(reflect.TypeOf(setlistfm.Country{}), "SetlistCountry")
	g.registerNamed(reflect.TypeOf(setlistfm.City{}), "SetlistCity")
	g.registerNamed(reflect.TypeOf(setlistfm.Venue{}), "SetlistVenue")
	g.registerNamed(reflect.TypeOf(setlistfm.Song{}), "SetlistSong")
	g.registerNamed(reflect.TypeOf(setlistfm.Set{}), "SetlistSet")
	g.registerNamed(reflect.TypeOf(setlistfm.Sets{}), "SetlistSets")
	g.registerNamed(reflect.TypeOf(setlistfm.Artist{}), "SetlistArtist")
	g.registerNamed(reflect.TypeOf(setlistfm.Setlist{}), "Setlist")

	// Register API DTO types
	g.registerNamed(reflect.TypeOf(apitypes.AuthUrlResponse{}), "AuthUrlResponse")
	g.registerNamed(reflect.TypeOf(apitypes.GetUserRequest{}), "GetUserRequest")
	g.registerNamed(reflect.TypeOf(apitypes.GetUserResponse{}), "GetUserResponse")
	g.registerNamed(reflect.TypeOf(apitypes.ArtistSearchRequest{}), "ArtistSearchRequest")
	g.registerNamed(reflect.TypeOf(apitypes.ArtistSearchResponse{}), "ArtistSearchResponse")
	g.registerNamed(reflect.TypeOf(apitypes.SetlistArtistsRequest{}), "SetlistArtistsRequest")
	g.registerNamed(reflect.TypeOf(apitypes.SetlistArtistsResponse{}), "SetlistArtistsResponse")
	g.registerNamed(reflect.TypeOf(apitypes.ArtistSetlistsRequest{}), "ArtistSetlistsRequest")
	g.registerNamed(reflect.TypeOf(apitypes.ArtistSetlistsResponse{}), "ArtistSetlistsResponse")
	g.registerNamed(reflect.TypeOf(apitypes.BuildPlaylistRequest{}), "BuildPlaylistRequest")
	g.registerNamed(reflect.TypeOf(apitypes.BuildPlaylistResponse{}), "BuildPlaylistResponse")

	content, err := g.generate()
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error generating types: %v\n", err)
		os.Exit(1)
	}

	targetPath := filepath.Join("src", "api", "types.gen.ts")
	if err := os.MkdirAll(filepath.Dir(targetPath), 0755); err != nil {
		fmt.Fprintf(os.Stderr, "Error creating directory: %v\n", err)
		os.Exit(1)
	}

	if err := os.WriteFile(targetPath, content, 0644); err != nil {
		fmt.Fprintf(os.Stderr, "Error writing file: %v\n", err)
		os.Exit(1)
	}

	fmt.Printf("Generated %s successfully (%d bytes)\n", targetPath, len(content))
}
